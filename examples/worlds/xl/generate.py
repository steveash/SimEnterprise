def _config(name: str, spec: dict[str, object], seed: int) -> str:
    lines = [
        f"# XL world {name}: {spec['what']}.",
        "# Generated by examples/worlds/xl/generate.py; edit the generator, not this file.",
        f"seed = {seed}",
        'worlds_root = "worlds"',
        "",
        "[company]",
        f"name = {json.dumps(spec['company'])}",
        f"vertical = {json.dumps(spec['vertical'])}",
        'size = "enterprise"',
        "",
        "[simulation]",
        "period_start = 2024-01-08",
        "period_end = 2026-12-25",
        "",
        "[model]",
        'backend = "bedrock"',
        'name = "us.anthropic.claude-haiku-5-5"',
        'offline_backend = "synth"',
        "",
        "[scale]",
        "max_concurrency = 16",
        "cost_ceiling_usd = 60.0",
        "",
    ]
    for dept in spec["departments"]:  # type: ignore[attr-defined]
        lines += ["[[departments]]", f'archetype = "{dept}"']
    lines += [
        "",
        "[facts]",
        "per_project = 10",
        "change_rate = 0.6",
        "max_versions = 6",
        "stale_rate = 0.3",
        "conflict_rate = 0.1",
        "hedge_rate = 0.15",
        "cross_team = 0.9",
        "cross_team_stale_boost = 2.5",
        "retraction_rate = 0.3",
        "horizon_days = 1100",
        "entity_ids = true",
        "",
        "[org]",
        "project_names = true",
        'squads_per_team = "6..8"',
        "turnover_rate = 0.25",
        "transfer_rate = 0.12",
        "horizon_days = 1100",
        "",
        "[messiness]",
        "typo_rate = 0.02",
        "alias_rate = 0.35",
        "date_format_mix = 0.4",
        "duplicate_rate = 0.08",
        "drop_header_rate = 0.12",
        "filler_rate = 0.15",
        "",
        "[chat]",
        "rate = 0.4",
        "",
        "[formats]",
        "decks = true",
        "email = true",
        "invites = true",
        "",
        "[code]",
        "enabled = true",
        "",
        "[privacy]",
        f"sensitive_rate = {spec['privacy']}",
        "",
        "[data]",
        "scenarios = [" + ", ".join(json.dumps(s) for s in spec["data"]) + "]",  # type: ignore[attr-defined]
        "scale_factor = 2.0",
        "iterations = 2",
        "",
        "[data.messiness]",
        "null_rate = 0.03",
        "duplicate_rate = 0.02",
        "label_drift_rate = 0.1",
        "outlier_rate = 0.01",
        "schema_drift = true",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    for index, (name, spec) in enumerate(VARIANTS.items()):
        (HERE / f"{name}.toml").write_text(_config(name, spec, 7000 + index), encoding="utf-8")
    print(f"{len(VARIANTS)} configs")


if __name__ == "__main__":
    main()

def scaffold(
    templates_dir: Path,
    *,
    slug: str,
    kind: TemplateKind | str,
    name: str,
    description: str = "",
) -> Template:
    """Write ``<templates_dir>/<slug>/`` (``template.json`` + ``plugin.py`` + test).

    Raises :class:`FileExistsError` if the template directory already exists,
    and :class:`ValueError` for a malformed ``slug``. Returns the written
    (``unvalidated``) :class:`~enterprise_sim.templates.store.Template`.
    """
    _validate_slug(slug)
    kind = TemplateKind(kind)
    directory = template_dir(templates_dir, slug)
    if directory.exists():
        raise FileExistsError(f"template {slug!r} already exists at {directory}")
    directory.mkdir(parents=True)

    if kind is TemplateKind.DEPARTMENT:
        plugin_source = _department_plugin(slug, description)
        test_source = _department_test(slug)
    elif kind is TemplateKind.PLAYBOOK:
        plugin_source = _playbook_plugin(slug, description)
        test_source = _playbook_test(slug)
    else:
        plugin_source = _bundle_plugin(slug, description)
        test_source = _bundle_test(slug)

    (directory / "plugin.py").write_text(plugin_source, encoding="utf-8")
    (directory / f"test_{slug}.py").write_text(test_source, encoding="utf-8")

    stamp = now_iso()
    template = Template(
        slug=slug,
        name=name,
        kind=kind,
        description=description,
        created_at=stamp,
        updated_at=stamp,
    )
    write_template(templates_dir, template)
    return template


__all__ = ["scaffold"]
